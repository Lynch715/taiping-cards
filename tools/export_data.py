#!/usr/bin/env python3
"""CSV is authoritative. Validate references, emit typed JSON + compiled keyword AST."""
import argparse,csv,hashlib,json,sys
from pathlib import Path
from battle_sim import Data,exclusive_skills,ROOT
OUT=ROOT/'app/src/core/data'
NUMERIC={'feast':{'chapter','daily_limit','silver','exp'},'stage_level_overrides':{'assumed_level','source_accounts'},'heroes':{'tong','wu','zhi','su'},'characters':{'appearance_age','x_offset','height_scale'},'equipment':{'main_value','sub_value','enhance_max'},'enemy_units':{'tong','wu','zhi','su'},'stages':{'chapter','order','year','enemy_level','recommended_power','enemy_monarch_stars'},'progression_levels':{'level','exp_to_next','cumulative_to_reach'},'star_up':{'star_from','star_to','shards','silver','level_cap_before','level_cap_after'},'equip_enhance':{'to_level','iron','silver','salvage_iron'},'economy_chapters':{'chapter','target_level_end','target_days','exp_needed_team','idle_exp_per_hour','idle_silver_per_hour','idle_iron_per_hour','first_clear_exp','first_clear_silver','first_clear_iron','first_clear_recruit_ticket','sweep_exp','sweep_silver','sweep_shards'}}
NULLABLE={('characters','appearance_age'),('stages','enemy_level'),('stages','recommended_power'),('stages','enemy_monarch_stars'),('equip_enhance','salvage_iron')}
ENUMS={('heroes','rarity'):['SSR','SR','R'],('characters','rarity_draft'):['SSR','SR','R'],('heroes','faction'):['taiping','qing','dual'],('characters','faction'):['taiping','qing','dual'],('stages','campaign'):['taiping','qing'],('stages','history_result'):['胜','败'],('starter_cards','campaign'):['taiping','qing'],('enemy_units','faction'):['taiping','qing']}
NAMES={'feast':'FeastRule','stage_level_overrides':'StageLevelOverride','heroes':'Hero','characters':'CharacterArt','skills':'Skill','bonds':'BondRow','equipment':'Equipment','equipment_sets':'EquipmentSet','exclusive_equipment':'ExclusiveEquipment','enemy_units':'EnemyUnit','stages':'Stage','starter_cards':'StarterCards','progression_levels':'ProgressionLevel','star_up':'StarUp','recruit':'RecruitRule','equip_enhance':'EquipEnhance','economy_chapters':'EconomyChapter'}
ART_ONLY_TABLES={'npc_portraits','equipment_icons'}  # Build-time mappings; never enter combat data or golden manifests.
def build():
 d=Data();assert not d.audit,d.audit;db={};types=['// Generated by tools/export_data.py. Do not edit.']
 for file in sorted((ROOT/'data').glob('*.csv')):
  name=file.stem
  if name in ART_ONLY_TABLES:continue
  with file.open(encoding='utf-8-sig',newline='') as f:reader=csv.DictReader(f);cols=list(reader.fieldnames);rows=list(reader)
  assert name in NAMES,f'Unknown table schema: {name}'
  nums=NUMERIC.get(name,set())
  for row in rows:
   for k in nums:
    if row[k]=='' and (name,k) in NULLABLE:row[k]=None;continue
    if row[k]=='':raise ValueError(f'{name}.{k} cannot be empty')
    n=float(row[k]);row[k]=int(n) if n.is_integer() else n
  if 'id' in cols:assert len({r['id'] for r in rows})==len(rows),f'Duplicate {name} id'
  db[name]=rows
  types+=['export interface '+NAMES[name]+' {']+[f'  {k}: '+(' | '.join(repr(v) for v in ENUMS[(name,k)]) if (name,k) in ENUMS else 'number | null' if (name,k) in NULLABLE else 'number' if k in nums else 'string')+';' for k in cols]+['}']
 feast=db.get('feast',[])
 assert len(feast)==16 and {(r['profile'],r['chapter'])for r in feast}=={(p,c)for p in ['conservative','aggressive']for c in range(1,9)},'Expected both feast profiles and eight chapters'
 for profile in ['conservative','aggressive']:
  rules=sorted((r for r in feast if r['profile']==profile),key=lambda r:r['chapter'])
  assert len({r['daily_limit']for r in rules})==1,'Daily feast limit must be chapter-independent'
  assert all(isinstance(r[k],int)and r[k]>0 for r in rules for k in ['silver','exp','daily_limit'])and max(r['daily_limit']for r in rules)<=10,'Invalid feast amount'
  assert all(a['silver']<b['silver']for a,b in zip(rules,rules[1:])),'Feast price must increase with chapter'
 h=d.heroes;skills=d.skills
 for hero in h.values():
  assert hero['rarity'] in {'SSR','SR','R'}
  assert hero['faction'] in {'taiping','qing','dual'}
  assert hero['troop'] in {'步','骑','水','火','谋','-'}
 assert all(x['valid'] for x in d.budget()),'Hero budget outside2.2'
 for bond in db['bonds']:
  assert all(i in h for i in bond['members'].replace('>',';').split(';'))
 npc={r['id'] for r in db['enemy_units']};ids=set(h)|npc
 for row in db['starter_cards']:
  cards=row['cards'].split(';');assert len(cards)==7 and len(set(cards))==7
  assert h[row['monarch']]['position']=='君主'
  for ident in cards:assert ident in h and h[ident]['position']!='君主' and h[ident]['faction']==row['campaign']
 assert len(db['stages'])==96 and len({r['stage_id'] for r in db['stages']})==96,'Expected 96 unique stages'
 assert {(r['campaign'],r['chapter'],r['order'])for r in db['stages']}=={(c,n,o)for c in ['taiping','qing']for n in range(1,9)for o in range(1,7)},'Each campaign requires 8 chapters of 6 stages'
 overrides=db.get('stage_level_overrides',[]);assert len({r['stage_id']for r in overrides})==len(overrides),'Duplicate stage level override'
 for override in overrides:
  assert override['stage_id'] in {r['stage_id']for r in db['stages']} and 1<=override['assumed_level']<=100 and isinstance(override['source_accounts'],int) and override['source_accounts']>0,'Invalid stage level override'
 level_overrides={r['stage_id']:r['assumed_level']for r in overrides}
 for row in db['stages']:
  assert row['history_result'] in {'胜','败'},'Invalid history_result'
  assert len(row['enemies'].split(','))==5
  if row['enemy_level'] is not None:
   ch=row['chapter'];end=db['economy_chapters'][ch-1]['target_level_end'];start=10 if ch==1 else db['economy_chapters'][ch-2]['target_level_end'];assumed=level_overrides.get(row['stage_id'],start+(end-start)*(row['order']-1)/5)
   assert max(1,assumed-5)-1e-7<=row['enemy_level']<=min(100,assumed+10)+1e-7,'Enemy level outside v0.2 bounds'
  assert all(x in ids for x in row['enemies'].split(','))
  assert not row['enemy_monarch'] or h[row['enemy_monarch']]['position']=='君主'
  assert (row['chapter']>1 and row['enemy_level'] is None) or (row['enemy_level'] is not None and 1<=row['enemy_level']<=100)
  stars=[int(s) for s in row['enemy_stars'].split(';')];assert len(stars)==5 and all(1<=s<=6 for s in stars),'Invalid enemy stars'
  assert (row['enemy_monarch_stars'] is None and not row['enemy_monarch']) or (row['enemy_monarch'] and row['enemy_monarch_stars'] is not None and 1<=row['enemy_monarch_stars']<=6),'Invalid enemy monarch stars'
  if row.get('reward_unlock'):
   reward=h[row['reward_unlock']];assert reward['faction'] in {row['campaign'],'dual'},'Invalid chapter reward faction'
   if row['chapter']<=2:assert reward['position']!='君主','Playable chapter reward must be a combat hero'
 compiled={'skills':d.cache,'bonds':{r['bond_id']:r['_ast'] for r in d.bonds},'sets':d.set_ast,'exclusives':{}}
 for hero in h.values():
  if hero['id'] not in d.exclusives:continue
  a,p,extra,unknown=exclusive_skills(d,hero,True);assert not unknown,(hero['id'],unknown)
  compiled['exclusives'][hero['id']]={'active':a,'passive':p,'extra':extra}
 db['compiled']=compiled
 files={f'{k}.json':json.dumps(v,ensure_ascii=False,indent=2)+'\n' for k,v in db.items()}
 files['types.ts']='\n'.join(types)+'\n'
 imports=[]
 for k in db:imports.append(f"import {k} from './{k}.json';")
 files['index.ts']='\n'.join(imports)+"\nimport type { Database } from '../battle/types';\nexport const database = {"+','.join(db)+"} as unknown as Database;\nexport * from './types';\n"
 hashes={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted((ROOT/'data').glob('*.csv')) if p.stem not in ART_ONLY_TABLES}
 files['manifest.json']=json.dumps({'source_sha256':hashes,'rows':{k:len(v) for k,v in db.items() if isinstance(v,list)}},ensure_ascii=False,indent=2)+'\n'
 return files
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args();files=build();OUT.mkdir(parents=True,exist_ok=True)
 stale=[n for n,v in files.items() if not (OUT/n).exists() or (OUT/n).read_text()!=v]
 if args.check:
  if stale:raise SystemExit('Generated data stale: '+', '.join(stale)+'; run npm run data')
 else:
  for n,v in files.items():(OUT/n).write_text(v)
 print(json.dumps({'valid':True,'files':len(files),'stale':stale if args.check else []},ensure_ascii=False))
